BEGIN;

-- Fase 1: trazabilidad independiente de las asignaciones de roles y representantes.
-- Requiere 005_multirole_y_representantes.sql. No modifica ni elimina datos existentes.

ALTER TABLE public.usuario_rol
    ADD COLUMN IF NOT EXISTS fecha_revocacion TIMESTAMP WITHOUT TIME ZONE NULL,
    ADD COLUMN IF NOT EXISTS revocado_por BIGINT NULL,
    ADD COLUMN IF NOT EXISTS motivo_revocacion TEXT NULL;

DO $migration$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_rol_revocado_por') THEN
        ALTER TABLE public.usuario_rol
            ADD CONSTRAINT fk_usuario_rol_revocado_por
            FOREIGN KEY (revocado_por) REFERENCES public.usuario(id_usuario);
    END IF;
END $migration$;

ALTER TABLE public.usuario_establecimiento
    ADD COLUMN IF NOT EXISTS asignado_por BIGINT NULL,
    ADD COLUMN IF NOT EXISTS fecha_revocacion TIMESTAMP WITHOUT TIME ZONE NULL,
    ADD COLUMN IF NOT EXISTS revocado_por BIGINT NULL,
    ADD COLUMN IF NOT EXISTS motivo_revocacion TEXT NULL;

DO $migration$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_establecimiento_asignado_por') THEN
        ALTER TABLE public.usuario_establecimiento
            ADD CONSTRAINT fk_usuario_establecimiento_asignado_por
            FOREIGN KEY (asignado_por) REFERENCES public.usuario(id_usuario);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_establecimiento_revocado_por') THEN
        ALTER TABLE public.usuario_establecimiento
            ADD CONSTRAINT fk_usuario_establecimiento_revocado_por
            FOREIGN KEY (revocado_por) REFERENCES public.usuario(id_usuario);
    END IF;
END $migration$;

CREATE TABLE IF NOT EXISTS public.auditoria_usuario_rol (
    id_auditoria_usuario_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_rol BIGINT NULL,
    id_usuario BIGINT NOT NULL,
    id_rol BIGINT NOT NULL,
    actor_id BIGINT NULL,
    accion VARCHAR(20) NOT NULL,
    fecha_evento TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo TEXT NULL,
    CONSTRAINT ck_auditoria_usuario_rol_accion
        CHECK (accion IN ('ASIGNADO', 'REVOCADO', 'REACTIVADO')),
    CONSTRAINT fk_auditoria_usuario_rol_asignacion
        FOREIGN KEY (id_usuario_rol) REFERENCES public.usuario_rol(id_usuario_rol) ON DELETE SET NULL,
    CONSTRAINT fk_auditoria_usuario_rol_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario),
    CONSTRAINT fk_auditoria_usuario_rol_rol
        FOREIGN KEY (id_rol) REFERENCES public.rol(id_rol),
    CONSTRAINT fk_auditoria_usuario_rol_actor
        FOREIGN KEY (actor_id) REFERENCES public.usuario(id_usuario)
);

CREATE TABLE IF NOT EXISTS public.auditoria_usuario_establecimiento (
    id_auditoria_usuario_establecimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_establecimiento BIGINT NULL,
    id_usuario BIGINT NOT NULL,
    id_establecimiento BIGINT NOT NULL,
    actor_id BIGINT NULL,
    accion VARCHAR(20) NOT NULL,
    fecha_evento TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo TEXT NULL,
    CONSTRAINT ck_auditoria_usuario_establecimiento_accion
        CHECK (accion IN ('ASIGNADO', 'REVOCADO', 'REACTIVADO')),
    CONSTRAINT fk_auditoria_usuario_establecimiento_asignacion
        FOREIGN KEY (id_usuario_establecimiento)
        REFERENCES public.usuario_establecimiento(id_usuario_establecimiento) ON DELETE SET NULL,
    CONSTRAINT fk_auditoria_usuario_establecimiento_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario),
    CONSTRAINT fk_auditoria_usuario_establecimiento_establecimiento
        FOREIGN KEY (id_establecimiento)
        REFERENCES public.establecimiento(id_establecimiento),
    CONSTRAINT fk_auditoria_usuario_establecimiento_actor
        FOREIGN KEY (actor_id) REFERENCES public.usuario(id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_rol_usuario_fecha
    ON public.auditoria_usuario_rol (id_usuario, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_rol_actor_fecha
    ON public.auditoria_usuario_rol (actor_id, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_establecimiento_usuario_fecha
    ON public.auditoria_usuario_establecimiento (id_usuario, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_establecimiento_establecimiento_fecha
    ON public.auditoria_usuario_establecimiento (id_establecimiento, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_establecimiento_actor_fecha
    ON public.auditoria_usuario_establecimiento (actor_id, fecha_evento DESC);

-- Registrar el estado inicial migrado. actor_id queda NULL porque no existe
-- evidencia histórica confiable del usuario que realizó las asignaciones originales.
INSERT INTO public.auditoria_usuario_rol
    (id_usuario_rol, id_usuario, id_rol, actor_id, accion, fecha_evento, motivo)
SELECT ur.id_usuario_rol, ur.id_usuario, ur.id_rol, ur.asignado_por,
       'ASIGNADO', ur.fecha_asignacion, 'Registro inicial migrado; actor histórico no disponible'
FROM public.usuario_rol ur
WHERE NOT EXISTS (
    SELECT 1 FROM public.auditoria_usuario_rol a
    WHERE a.id_usuario_rol = ur.id_usuario_rol
      AND a.accion = 'ASIGNADO'
);

INSERT INTO public.auditoria_usuario_establecimiento
    (id_usuario_establecimiento, id_usuario, id_establecimiento, actor_id, accion, fecha_evento, motivo)
SELECT ue.id_usuario_establecimiento, ue.id_usuario, ue.id_establecimiento, ue.asignado_por,
       'ASIGNADO', ue.fecha_asignacion, 'Registro inicial migrado; actor histórico no disponible'
FROM public.usuario_establecimiento ue
WHERE NOT EXISTS (
    SELECT 1 FROM public.auditoria_usuario_establecimiento a
    WHERE a.id_usuario_establecimiento = ue.id_usuario_establecimiento
      AND a.accion = 'ASIGNADO'
);

INSERT INTO public.schema_version (version, descripcion)
VALUES (
    '006_auditoria_asignaciones',
    'Auditoria independiente de asignacion, revocacion y reactivacion de roles y representantes'
)
ON CONFLICT (version) DO NOTHING;

COMMIT;
