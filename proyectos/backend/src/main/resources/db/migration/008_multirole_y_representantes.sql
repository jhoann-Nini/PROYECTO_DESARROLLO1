BEGIN;

-- Fase 1: relaciones multirrol y representantes de establecimientos.
-- Las columnas antiguas usuario.id_rol y establecimiento.id_usuario
-- se conservan para mantener compatibilidad durante la transición.

CREATE TABLE IF NOT EXISTS public.usuario_rol (
    id_usuario_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_rol BIGINT NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_asignacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    asignado_por BIGINT NULL,
    CONSTRAINT uq_usuario_rol_usuario_rol UNIQUE (id_usuario, id_rol),
    CONSTRAINT fk_usuario_rol_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario),
    CONSTRAINT fk_usuario_rol_rol
        FOREIGN KEY (id_rol) REFERENCES public.rol(id_rol),
    CONSTRAINT fk_usuario_rol_asignado_por
        FOREIGN KEY (asignado_por) REFERENCES public.usuario(id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_usuario_rol_usuario_estado
    ON public.usuario_rol (id_usuario, estado);
CREATE INDEX IF NOT EXISTS idx_usuario_rol_rol_estado
    ON public.usuario_rol (id_rol, estado);

CREATE TABLE IF NOT EXISTS public.usuario_establecimiento (
    id_usuario_establecimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_establecimiento BIGINT NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_asignacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_establecimiento
        UNIQUE (id_usuario, id_establecimiento),
    CONSTRAINT fk_usuario_establecimiento_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario),
    CONSTRAINT fk_usuario_establecimiento_establecimiento
        FOREIGN KEY (id_establecimiento)
        REFERENCES public.establecimiento(id_establecimiento)
);

CREATE INDEX IF NOT EXISTS idx_usuario_establecimiento_usuario_estado
    ON public.usuario_establecimiento (id_usuario, estado);
CREATE INDEX IF NOT EXISTS idx_usuario_establecimiento_establecimiento_estado
    ON public.usuario_establecimiento (id_establecimiento, estado);

-- Migrar todas las asignaciones de rol actuales sin modificar usuario.id_rol.
INSERT INTO public.usuario_rol (
    id_usuario, id_rol, estado, fecha_asignacion, asignado_por
)
SELECT
    u.id_usuario,
    u.id_rol,
    TRUE,
    u.fecha_registro,
    NULL
FROM public.usuario u
WHERE u.id_rol IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM public.usuario_rol ur
      WHERE ur.id_usuario = u.id_usuario
        AND ur.id_rol = u.id_rol
  );

-- Migrar los representantes actuales desde establecimiento.id_usuario.
INSERT INTO public.usuario_establecimiento (
    id_usuario, id_establecimiento, estado, fecha_asignacion
)
SELECT
    e.id_usuario,
    e.id_establecimiento,
    TRUE,
    CURRENT_TIMESTAMP
FROM public.establecimiento e
WHERE e.id_usuario IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM public.usuario_establecimiento ue
      WHERE ue.id_usuario = e.id_usuario
        AND ue.id_establecimiento = e.id_establecimiento
  );

INSERT INTO public.schema_version (version, descripcion)
VALUES (
    '008_multirole_y_representantes',
    'Relaciones muchos-a-muchos Usuario-Rol y Usuario-Establecimiento con migracion de asignaciones existentes'
)
ON CONFLICT (version) DO NOTHING;

COMMIT;
