BEGIN;

CREATE TABLE IF NOT EXISTS public.reporte_oferta
(
  id_reporte          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  id_producto         BIGINT      NOT NULL,
  id_establecimiento  BIGINT      NOT NULL,
  id_usuario          BIGINT      NOT NULL,

  motivo              VARCHAR(30) NOT NULL,
  descripcion         TEXT,

  estado              VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',

  fecha_creacion      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT fk_reporte_oferta_producto_establecimiento
    FOREIGN KEY (id_producto, id_establecimiento)
      REFERENCES public.producto_establecimiento
        (id_producto, id_establecimiento),

  CONSTRAINT fk_reporte_oferta_usuario
    FOREIGN KEY (id_usuario)
      REFERENCES public.usuario (id_usuario),

  CONSTRAINT chk_reporte_oferta_motivo
    CHECK (
      motivo IN (
        'precio_incorrecto',
        'enlace_incorrecto'
      )
    ),

  CONSTRAINT chk_reporte_oferta_estado
    CHECK (
      estado IN (
        'PENDIENTE',
        'EN_REVISION',
        'ACEPTADO',
        'RECHAZADO'
      )
    )
);

CREATE INDEX IF NOT EXISTS idx_reporte_oferta_estado
  ON public.reporte_oferta (estado);

CREATE INDEX IF NOT EXISTS idx_reporte_oferta_usuario
  ON public.reporte_oferta (id_usuario);

CREATE INDEX IF NOT EXISTS idx_reporte_oferta_producto_establecimiento
  ON public.reporte_oferta (id_producto, id_establecimiento);

ALTER TABLE public.reporte_oferta ENABLE ROW LEVEL SECURITY;

INSERT INTO public.schema_version (version, descripcion)
VALUES (
  '018_reportes_ofertas',
  'Crea la tabla para reportes de precios y enlaces incorrectos de ofertas'
)
ON CONFLICT (version) DO NOTHING;

COMMIT;
